#!/usr/bin/env python3
"""Turns an Ableton Simpler preset (.adv) into the C++ template TEAROUT ENGINE fills in for DRAG INSTRUMENT.

Usage: python3 -I tools/make_simpler_template.py tools/templates/simpler-template.adv src/core/SimplerTemplate.inc

The source template comes from Ableton-Device-Creator (MIT, (c) Ben Juodvalkis):
https://github.com/ben-juodvalkis/Ableton-Device-Creator
Values that change per sound are replaced with @@MARKERS@@; the header is set to Live 11 so Live 11 opens it.
"""
import gzip
import sys
import xml.etree.ElementTree as ET

LIVE11_HEADER = ('<Ableton MajorVersion="5" MinorVersion="11.0_433" SchemaChangeCount="3" '
                 'Creator="Ableton Live 11.0" Revision="">')


def setv(elem, path, value):
    node = elem.find(path)
    if node is None:
        raise SystemExit("template is missing " + path)
    node.set("Value", value)


def main(src, dst):
    raw = open(src, "rb").read()
    xml = gzip.decompress(raw).decode("utf-8") if raw[:2] == b"\x1f\x8b" else raw.decode("utf-8")
    root = ET.fromstring(xml)
    s = root.find("OriginalSimpler")
    # Live 12 only
    for tag in ("MpePitchBendUsesTuning",):
        n = s.find(tag)
        if n is not None:
            s.remove(n)
    setv(s, "UserName", "@@USERNAME@@")
    part = s.find("Player/MultiSampleMap/SampleParts/MultiSamplePart")
    setv(part, "Name", "@@NAME@@")
    setv(part, "RootKey", "@@ROOT@@")
    setv(part, "SampleStart", "0")
    setv(part, "SampleEnd", "@@END@@")
    setv(part, "SustainLoop/Start", "@@LSTART@@")
    setv(part, "SustainLoop/End", "@@LEND@@")
    setv(part, "SustainLoop/Mode", "@@LMODE@@")
    setv(part, "SustainLoop/Crossfade", "0")
    setv(part, "ReleaseLoop/Start", "0")
    setv(part, "ReleaseLoop/End", "@@END@@")
    ref = part.find("SampleRef")
    setv(ref, "FileRef/RelativePathType", "0")
    setv(ref, "FileRef/RelativePath", "")
    setv(ref, "FileRef/Path", "@@PATH@@")
    setv(ref, "FileRef/OriginalFileSize", "@@SIZE@@")
    setv(ref, "FileRef/OriginalCrc", "0")
    setv(ref, "DefaultDuration", "@@FRAMES@@")
    setv(ref, "DefaultSampleRate", "@@RATE@@")
    setv(part, "SampleWarpProperties/IsWarped", "false")
    g = s.find("Globals")
    setv(g, "NumVoices", "@@VOICES@@")
    setv(g, "RetriggerMode", "@@RETRIGGER@@")
    setv(g, "PortamentoMode/Manual", "@@PMODE@@")
    setv(g, "PortamentoTime/Manual", "@@PTIME@@")
    setv(g, "PlaybackMode", "0")  # Classic
    env = s.find("VolumeAndPan/Envelope")
    setv(env, "AttackTime/Manual", "@@ATTACK@@")
    setv(env, "ReleaseTime/Manual", "@@RELEASE@@")
    setv(env, "SustainLevel/Manual", "1")
    setv(s, "VolumeAndPan/Volume/Manual", "@@VOLUME@@")
    setv(s, "Filter/IsOn/Manual", "false")

    body = ET.tostring(root, encoding="unicode")
    body = body[body.index(">") + 1:]  # drop the original <Ableton ...> opening tag
    text = '<?xml version="1.0" encoding="UTF-8"?>\n' + LIVE11_HEADER + body
    data = text.encode("utf-8")
    with open(dst, "w") as f:
        f.write("// Generated by tools/make_simpler_template.py - do not edit.\n")
        f.write("// Simpler preset template; source: Ableton-Device-Creator (MIT, (c) Ben Juodvalkis).\n")
        f.write("static const unsigned char kSimplerTemplate[] = {\n")
        for i in range(0, len(data), 24):
            f.write("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write("};\n")
        f.write("static const size_t kSimplerTemplateSize = %d;\n" % len(data))
    print("wrote", dst, len(data), "bytes")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
